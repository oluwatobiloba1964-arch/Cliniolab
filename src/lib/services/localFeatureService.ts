/** A single cache entry. expiresAt = epoch ms; 0 means never expires. */
interface CacheEntry<T> {
  expiresAt: number;
  data: T;
  savedAt: number;
}

/** Read a cached entry. Returns null if missing, corrupt, or expired. */
export function readCache<T>(key: string): T | null {
  if (typeof window === 'undefined') return null;
  try {
    const raw = window.localStorage.getItem(key);
    if (!raw) return null;
    const entry = JSON.parse(raw) as CacheEntry<T>;
    if (!entry || typeof entry !== 'object') return null;
    // 0 means never expires - useful for purely local data.
    if (entry.expiresAt !== 0 && entry.expiresAt < Date.now()) {
      window.localStorage.removeItem(key);
      return null;
    }
    return entry.data;
  } catch {
    return null;
  }
}

/** Write a cache entry. ttlMs = 0 means never expires. */
export function writeCache<T>(key: string, data: T, ttlMs: number): boolean {
  if (typeof window === 'undefined') return false;
  try {
    const entry: CacheEntry<T> = {
      expiresAt: ttlMs === 0 ? 0 : Date.now() + ttlMs,
      data,
      savedAt: Date.now(),
    };
    window.localStorage.setItem(key, JSON.stringify(entry));
    return true;
  } catch {
    // Quota exceeded or storage disabled - caching is best-effort.
    return false;
  }
}

/** Remove a cache entry. */
export function clearCache(key: string): void {
  if (typeof window === 'undefined') return;
  try {
    window.localStorage.removeItem(key);
  } catch {
    // Ignore.
  }
}

/**
 * The core localStorage-first helper.
 *
 *   1. Read localStorage. If fresh, return immediately (no network).
 *   2. If stale / missing, call the fetcher (which may hit the API).
 *   3. On success, write back to localStorage.
 *
 * The fetcher is only ever called when localStorage does not have fresh
 * data. This is the rule the project follows everywhere: local first,
 * DB as fallback, write back to local for next load.
 */
export async function getOrFetch<T>(
  key: string,
  fetcher: () => Promise<T>,
  ttlMs: number,
): Promise<T> {
  const cached = readCache<T>(key);
  if (cached !== null) return cached;

  const fresh = await fetcher();
  writeCache(key, fresh, ttlMs);
  return fresh;
}

/**
 * Synchronous read + write helper for purely local data (no DB source).
 * Use for features where the data is generated by the user's own
 * activity on this device (study time, focus minutes, confidence
 * ratings, bookmarks saved while logged out).
 */
export function readLocal<T>(key: string, fallback: T): T {
  if (typeof window === 'undefined') return fallback;
  try {
    const raw = window.localStorage.getItem(key);
    if (!raw) return fallback;
    return JSON.parse(raw) as T;
  } catch {
    return fallback;
  }
}

export function writeLocal<T>(key: string, value: T): boolean {
  if (typeof window === 'undefined') return false;
  try {
    window.localStorage.setItem(key, JSON.stringify(value));
    return true;
  } catch {
    return false;
  }
}

/** Append an item to a list-valued local key, capped at maxItems. */
export function appendLocal<T extends { id?: string; at?: number }>(
  key: string,
  item: T,
  maxItems = 200,
): T[] {
  const list = readLocal<T[]>(key, []);
  list.unshift(item);
  // Dedup by id if present.
  const seen = new Set<string>();
  const deduped = list.filter((x) => {
    if (x.id && seen.has(x.id)) return false;
    if (x.id) seen.add(x.id);
    return true;
  });
  const capped = deduped.slice(0, maxItems);
  writeLocal(key, capped);
  return capped;
}

/** Default TTLs (mirrors publicFetch.ts conventions). */
export const TTL = {
  SHORT: 30_000, // 30s - fast-changing data
  LIST: 5 * 60_000, // 5 min - public listing pages
  CONFIG: 15 * 60_000, // 15 min - config / flags
  LONG: 60 * 60_000, // 1 hour - rarely changing content
  NEVER: 0, // local-only data, never expires
} as const;
