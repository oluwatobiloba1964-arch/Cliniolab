'use client';

/**
 * Central localStorage-first cache + per-feature store.
 *
 * Cache rule (project-wide):
 *   When a page loads, read localStorage FIRST. If the data is fresh
 *   (TTL not expired) and present, render immediately with NO database
 *   or API call. If localStorage is empty / stale / corrupt, fall back
 *   to the network fetcher. After a successful fetch, write the result
 *   back to localStorage so the next load is instant.
 *
 * Nothing here ever writes to the database. Every entry is browser-only.
 *
 * Each feature owns its own key so a corrupt store in one feature
 * cannot take the others down with it (same pattern as
 * localExtrasService.ts).
 */

